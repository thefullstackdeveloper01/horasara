/**
 * panchang-standalone.js — Prints a full "Daily Panchang" report for a
 * given date + place (not tied to a person's birth). Pure rendering only;
 * all values come from R.panchanga, which is computed by the same
 * src/panchanga/panchanga.js#calcPanchanga() used for Kundali Reading —
 * no duplicate astronomy logic.
 */
import { box, section, kv, C } from '../console-ui.js';
import { normalizeElapsedMs } from './reportTiming.js';

function timeOnly(dtStr) {
  if (!dtStr) return 'N/A';
  return dtStr.split(' ').slice(-1)[0];
}

function rangeOf(period) {
  if (!period) return 'N/A (no sunrise/sunset at this location/date)';
  // NOTE: rahuKaal/yamaganda/gulikaKaal only have start/end (already
  // formatted strings). brahmaMuhurta/vijayaMuhurta/godhuliMuhurta/
  // nishitaKaal have BOTH: start/end as raw JD-fraction numbers (for
  // programmatic use) AND startFormatted/endFormatted as display strings.
  // Prefer the *Formatted string when present; only fall back to
  // start/end when there is no Formatted variant.
  const start = period.startFormatted ?? period.start;
  const end = period.endFormatted ?? period.end;
  return `${timeOnly(start)} - ${timeOnly(end)}`;
}

export function printPanchangStandalone(R, elapsedMs) {
  elapsedMs = normalizeElapsedMs(elapsedMs);
  console.clear?.();
  box('🕉️   DAILY PANCHANG — दैनिक पंचांग  🕉️');
  console.log('');
  kv('Date', `${String(R.meta.day).padStart(2, '0')}-${String(R.meta.month).padStart(2, '0')}-${R.meta.year}`);
  kv('Place', `${R.meta.place || `Coordinates only (Lat ${R.meta.lat}, Lon ${R.meta.lon})`}  (Lat ${R.meta.lat}, Lon ${R.meta.lon}, TZ +${R.meta.tz})`);
  kv('Report Generated', new Date().toLocaleString());
  kv('Calculation Time', `${elapsedMs.toFixed(3)} ms`);

  const pg = R.panchanga;

  section('THE FIVE LIMBS — पञ्चाङ्ग');
  kv('Tithi', `${pg.tithi.name} (${pg.tithi.paksha}) — ${pg.tithi.progress} complete, ends ${timeOnly(pg.tithi.endsAt)}`);
  kv('Vara (Weekday)', `${pg.vara.name} / ${pg.vara.hindi}  (Lord: ${pg.vara.lord})`);
  kv('Nakshatra', `${pg.nakshatra.name}  Pada ${pg.nakshatra.pada}  (Lord: ${pg.nakshatra.lord}, Deity: ${pg.nakshatra.deity}) — ends ${timeOnly(pg.nakshatra.endsAt)}`);
  kv('Yoga', `${pg.yoga.name} (${pg.yoga.nature}) — ends ${timeOnly(pg.yoga.endsAt)}`);
  kv('Karana', pg.karana.name);

  section('SUN, MOON & DAY LENGTH');
  kv('Moon Sign (Rashi)', `${pg.moonSign}  (Lord: ${pg.moonSignLord})`);
  kv('Sun Sign', pg.sunSign);
  kv('Sunrise', timeOnly(pg.sunrise));
  kv('Sunset', timeOnly(pg.sunset));
  kv('Day Duration', pg.dayDuration);

  section('INAUSPICIOUS PERIODS — अशुभ काल');
  kv('Rahu Kaal', rangeOf(pg.rahuKaal));
  kv('Yamaganda', rangeOf(pg.inauspiciousPeriods?.find(p => p.name === 'Yamaganda')));
  kv('Gulika Kaal', rangeOf(pg.inauspiciousPeriods?.find(p => p.name === 'Gulika Kaal')));

  section('AUSPICIOUS MUHURTAS — शुभ मुहूर्त');
  kv('Brahma Muhurta', rangeOf(pg.brahmaMuhurta) + (pg.brahmaMuhurta ? `  — ${pg.brahmaMuhurta.desc}` : ''));
  kv('Abhijit Muhurta', pg.abhijitMuhurta ? `${timeOnly(pg.abhijitMuhurta.startFormatted)} - ${timeOnly(pg.abhijitMuhurta.endFormatted)}` : 'N/A');
  kv('Vijaya Muhurta', rangeOf(pg.vijayaMuhurta) + (pg.vijayaMuhurta ? `  — ${pg.vijayaMuhurta.desc}` : ''));
  kv('Godhuli Muhurta', rangeOf(pg.godhuliMuhurta) + (pg.godhuliMuhurta ? `  — ${pg.godhuliMuhurta.desc}` : ''));
  kv('Nishita Kaal', rangeOf(pg.nishitaKaal) + (pg.nishitaKaal ? `  — ${pg.nishitaKaal.desc}` : ''));
  kv('Amrit Nakshatra Today', pg.isAmritNakshatra ? (C.green + 'Yes — favorable Nakshatra' + C.reset) : 'No');

  console.log('');
  box('✨  END OF DAILY PANCHANG — पंचांग समाप्त  ✨');
  console.log(C.dim + '\nGenerated by JyotiVeda V1 — Vedic Astrology Engine\n' + C.reset);
}
