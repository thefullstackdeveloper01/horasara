function helioToGeo(planetLBR, earthLBR) {
  const { L: Lp, B: Bp, R: Rp } = planetLBR;
  const { L: Le, B: Be, R: Re } = earthLBR;

  const xp = Rp * cos(Bp) * cos(Lp);
  const yp = Rp * cos(Bp) * sin(Lp);
  const zp = Rp * sin(Bp);

  const xe = Re * cos(Be) * cos(Le);
  const ye = Re * cos(Be) * sin(Le);
  const ze = Re * sin(Be);

  const x = xp - xe;
  const y = yp - ye;
  const z = zp - ze;

  const delta = sqrt(x * x + y * y + z * z);
  let lambda = atan2(y, x) * DEG;
  const beta = atan2(z, sqrt(x * x + y * y)) * DEG;
  lambda = norm360(lambda);

  return { longitude: lambda, latitude: beta, distance: delta };
}

// FK5 correction to ecliptic longitude (Meeus p.151)
function fk5Correction(lambda, beta, jd) {
  const Tc = T(jd);
  const Lp = lambda - 1.397 * Tc - 0.00031 * Tc * Tc;
  const dLambda = -0.09033 / 3600
    + 0.03916 / 3600 * (cos(Lp * RAD) - sin(Lp * RAD)) * tan(beta * RAD);
  return dLambda;
}

// ─── ABERRATION (Meeus Ch.23, eq. 23.2 — full two-body formula) ──────────────
const ABERRATION_KAPPA = 20.49552 / 3600; // constant of aberration, degrees

function aberrationCorrection(lambda, beta, sunLong, jde) {
  const Tc = T(jde);
  const e = 0.016708634 - 0.000042037 * Tc - 0.0000001267 * Tc * Tc;
  const piLon = norm360(102.93735 + 1.71946 * Tc + 0.00046 * Tc * Tc) * RAD;
  const lam = lambda * RAD;
  const bet = beta * RAD;
  const sunL = sunLong * RAD;
  const k = ABERRATION_KAPPA;

  const dLambda = (-k * cos(sunL - lam) + e * k * cos(piLon - lam)) / cos(bet);
  const dBeta = -k * sin(bet) * (sin(sunL - lam) - e * sin(piLon - lam));
  return { dLambda, dBeta };
}

function sunAberration(earthR) {
  return -(20.4898 / 3600) / earthR;
}

