// Mean obliquity of ecliptic (Meeus Ch.22)
export function meanObliquity(jd) {
  if (!isFiniteNum(jd)) return 23.4392911; // J2000 fallback
  const Tc = T(jd);
  const eps0 = 23 + 26 / 60 + 21.448 / 3600
    - (46.8150 * Tc + 0.00059 * Tc * Tc - 0.001813 * Tc * Tc * Tc) / 3600;
  return eps0;
}

export function trueObliquity(jd) {
  if (!isFiniteNum(jd)) return meanObliquity(2451545.0);
  const { deps } = nutation(jd);
  return meanObliquity(jd) + deps;
}

