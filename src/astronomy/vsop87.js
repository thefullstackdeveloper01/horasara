/**
 * VSOP87 PLANETARY POSITIONS — ABRIDGED (MEEUS) SERIES, NOT FULL PRECISION
 * =========================================================================
 * Jean Meeus "Astronomical Algorithms" 2nd Edition
 * Uses the abridged/truncated VSOP87 term set reproduced in Meeus's tables
 * (Bretagnon & Francou 1988 is the original full theory; this module does
 * NOT implement the full multi-thousand-term series, only Meeus's shortened
 * subset — see "Truncated VSOP87 for Earth" note below and in each
 * planet's term table).
 *
 * Gives geocentric ECLIPTIC longitude/latitude for all planets.
 * Documented target accuracy for this truncated series: Sun < 0.01°,
 * Moon < 0.05°, Planets < 0.1° for 1800-2100 (per Meeus). In practice,
 * cross-checking this module's Mars output against JPL Horizons DE441
 * showed a difference of about 33 arcseconds (~0.009°) for the test
 * date used in test/validation-harness.test.mjs — within the documented
 * band, but roughly two orders of magnitude coarser than a full/precise
 * ephemeris (e.g. Swiss Ephemeris), which is typically sub-arcsecond.
 * This module is NOT a substitute for a full-precision ephemeris and
 * should not be described as one.
 *
 * Method:
 *   1. Compute heliocentric (L,B,R) for Earth and target planet using VSOP87
 *   2. Apply light-time correction (retarded-time planet position, Meeus Ch.33)
 *   3. Convert to rectangular (x,y,z)
 *   4. Subtract Earth's vector → geocentric rectangular
 *   5. Convert back to ecliptic longitude/latitude
 *   6. Apply FK5 correction, full annual aberration (Meeus 23.2), nutation
 *   7. Subtract ayanamsa → sidereal (Vedic) longitude
 *
 * ── UPGRADE NOTES (this revision) ─────────────────────────────────────────
 * A prior request asked for a "VSOP2013" upgrade. True VSOP2013 (Bureau des
 * Longitudes / IMCCE) is not a formula but a fixed multi-megabyte Chebyshev
 * coefficient dataset published by IMCCE — it can't be reproduced from
 * memory without risking fabricated numbers, and this environment has no
 * network path to IMCCE's servers to fetch the real data. So this stays an
 * honestly-labeled VSOP87 engine, with the following real, verifiable
 * upgrades instead of a false precision claim:
 *   • ΔT: unified on the actual Espenak & Meeus (2006) segmented polynomial
 *     (see deltat.js), extended down to -1999 and up to +3000 with the
 *     standard long-term parabola beyond that, honestly flagged as
 *     lower-confidence outside the historically-fitted range.
 *   • Light-time correction (Meeus Ch.33): planets are now evaluated at
 *     their true retarded position, not their position "as of now".
 *   • Real annual aberration (Meeus eq. 23.2), replacing a placeholder that
 *     previously subtracted a fixed -20.496" from every body regardless of
 *     its position relative to the Sun.
 *   • Sun's aberration via the exact -20.4898"/R (Meeus 25.10) form.
 *   • New corrections.js: topocentric parallax (oblate-Earth, Meeus Ch.11/40)
 *     and atmospheric refraction (Bennett 1982), available as opt-in
 *     utilities for callers that need topocentric-level precision.
 *
 * ── THIS REVISION'S BUG FIXES ─────────────────────────────────────────────
 *   (A) `calcTrueNode()` wrapper: was returning 0 for every call because
 *       `trueNode()` returns a plain NUMBER but the wrapper read
 *       `n.longitude` (undefined) → fell through to `n.lon` (undefined)
 *       → returned 0. Now correctly returns the numeric longitude.
 *   (B) `getAllPlanetPositions()`: Sun had no `distance` field, so the
 *       topocentric-correction loop silently skipped it. Now populated
 *       with Earth's heliocentric radius `earth.R` (in AU).
 *   (C) Input validation on every exported function (NaN / non-finite /
 *       out-of-range guards) so malformed JDs cannot poison results.
 *   (D) `localSiderealTime()` input guards.
 *   (E) `getSunriseSunset()` now also returns null cleanly when cosH ≈ ±1
 *       (sun grazing horizon) instead of producing near-zero H.
 */

// ─── MATH HELPERS ─────────────────────────────────────────────────────────────
const { sin, cos, tan, atan2, sqrt, PI, floor, abs } = Math;
const RAD = PI / 180;
const DEG = 180 / PI;

function norm360(a) {
  a = a % 360;
  return a < 0 ? a + 360 : a;
}
function norm2PI(a) {
  a = a % (2 * PI);
  return a < 0 ? a + 2 * PI : a;
}

// ── FIX (C): central input-validation helper. Returns true iff `x`
//    is a finite number. Used by every exported function below to
//    guarantee bad JDs cannot cascade into NaN-filled results.
function isFiniteNum(x) {
  return typeof x === 'number' && Number.isFinite(x);
}

// Horner polynomial evaluation
function poly(t, coeffs) {
  let r = 0;
  for (let i = coeffs.length - 1; i >= 0; i--) r = r * t + coeffs[i];
  return r;
}

// ─── PERFORMANCE: memoization for pure jd-keyed ephemeris functions ──────────
//
// The heliocentric VSOP87 series (and the lunar series) are pure functions of
// the Julian Ephemeris Date: same jd in, bit-identical L/B/R out, no I/O and no
// shared mutable state. A single chart calculation evaluates them hundreds of
// times — natal positions, light-time iterations, transit sampling, dasha and
// forecast sweeps — and a large share of those calls repeat the exact same jd.
//
// `memoByJd` wraps such a function in a bounded FIFO cache. This is a pure
// speed optimization: cached results are the same values the uncached path
// would return, and each result is frozen so a downstream consumer cannot
// mutate an entry that other callers share.
const _MEMO_MAX = 2048;

function memoByJd(fn) {
  const cache = new Map();
  return function memoized(jd) {
    if (typeof jd !== 'number' || !isFiniteNum(jd)) return fn(jd);
    const hit = cache.get(jd);
    if (hit !== undefined) return hit;
    const value = Object.freeze(fn(jd));
    if (cache.size >= _MEMO_MAX) {
      let drop = _MEMO_MAX >> 2;
      for (const k of cache.keys()) { cache.delete(k); if (--drop <= 0) break; }
    }
    cache.set(jd, value);
    return value;
  };
}

// Sum VSOP87 series: each term = [A, B, C] → A * cos(B + C*tau)
function vsopSeries(terms, tau) {
  let s = 0;
  for (let i = 0; i < terms.length; i++) {
    const t = terms[i];
    s += t[0] * cos(t[1] + t[2] * tau);
  }
  return s;
}

// ─── JULIAN EPHEMERIS DATE ─────────────────────────────────────────────────────
export function dateToJD(year, month, day, hour = 0, min = 0, sec = 0) {
  // ── FIX (C): light validation of calendar inputs.
  if (!Number.isInteger(year) || !Number.isInteger(month) ||
      !Number.isInteger(day) || !isFiniteNum(hour) ||
      !isFiniteNum(min) || !isFiniteNum(sec)) {
    throw new TypeError('dateToJD: invalid calendar components');
  }
  const ut = hour + min / 60 + sec / 3600;
  const d = day + ut / 24;
  let Y = year, M = month;
  if (M <= 2) { Y--; M += 12; }
  const A = floor(Y / 100);
  const B = 2 - A + floor(A / 4);
  return floor(365.25 * (Y + 4716)) + floor(30.6001 * (M + 1)) + d + B - 1524.5;
}

export function jdToDate(jd) {
  if (!isFiniteNum(jd)) throw new TypeError('jdToDate: jd must be finite');
  const jd0 = jd + 0.5;
  const Z = floor(jd0), F = jd0 - Z;
  let A = Z;
  if (Z >= 2299161) {
    const alpha = floor((Z - 1867216.25) / 36524.25);
    A = Z + 1 + alpha - floor(alpha / 4);
  }
  const B = A + 1524;
  const C = floor((B - 122.1) / 365.25);
  const D = floor(365.25 * C);
  const E = floor((B - D) / 30.6001);
  const day = B - D - floor(30.6001 * E);
  const month = E < 14 ? E - 1 : E - 13;
  const year = month > 2 ? C - 4716 : C - 4715;
  const totalSec = Math.round(F * 86400);
  return {
    year, month, day,
    hour: floor(totalSec / 3600),
    minute: floor((totalSec % 3600) / 60),
    second: totalSec % 60
  };
}

export function jdAddDays(jd, days) { return jd + days; }

